"""Final report step: verify that generated results exist and summarise them."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from domainguard import config


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    args = parser.parse_args(argv)
    results = config.RESULTS_DIR / "results.md"
    if not results.exists() or not results.stat().st_size:
        raise FileNotFoundError("docs/results.md was not generated by evaluate.py")
    text = results.read_text(encoding="utf-8")
    for marker in ("Main metrics", "Ablations", "Prevalence-aware", "Leave-one-family-out",
                   "External real-data test", "Evasion tests", "Scanner on simulated"):
        if marker not in text:
            raise RuntimeError(f"results.md is missing section: {marker}")
    figures = sorted(path.name for path in config.FIGURES_DIR.glob("*.png"))
    if len(figures) < 5:
        raise RuntimeError(f"expected 5 figures, found {figures}")
    print(f"report verified: {results} ({len(text)} chars), figures: {', '.join(figures)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
